def get_global_focus_reset_style() -> str:
    """Disable the default dotted focus indicator generated by Qt."""
    return """
    *:focus {
        outline: none;
    }
    QWidget:focus {
        outline: none;
    }
    """

def create_gradient(start_color: str, end_color: str, direction: str = "vertical") -> str:
    """Create CSS gradient string"""
    if direction == "vertical":
        return f"qlineargradient(x1:0, y1:0, x2:0, y2:1, stop:0 {start_color}, stop:1 {end_color})"
    elif direction == "horizontal":
        return f"qlineargradient(x1:0, y1:0, x2:1, y2:0, stop:0 {start_color}, stop:1 {end_color})"
    elif direction == "diagonal":
        return f"qlineargradient(x1:0, y1:0, x2:1, y2:1, stop:0 {start_color}, stop:1 {end_color})"
    else:
        return start_color

